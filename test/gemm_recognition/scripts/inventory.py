#!/usr/bin/env python3
"""
inventory.py -- the per-case inventory of the showcase set: for every case,
its file, purpose, specified expectation and its basis, the affine index
forms and the loop bounds/steps it covers, whether the test framework has
actually executed it (from the latest report), and the open spec question
it depends on, if any.

    python3 scripts/inventory.py [--report reports/latest_soft.json] [--out showcase/INVENTORY.md]

The expectation column is the SPECIFICATION layer of showcase/manifest.json
(set by the mathematics and README.md section 2), never the compiler's
output; the execution column is what reports/latest_<mode>.json recorded.
Writes showcase/INVENTORY.md and showcase/inventory.json (both writable
documents, not test sources).
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))

EXPECT_TEXT = {
    "ACCEPT": "must be ACCEPTED (recognized and offloaded)",
    "REJECT": "must be REJECTED (not a dense GEMM of its operands)",
    "OUT_OF_SCOPE": "legal GEMM, documented limitation: must be refused, never called 'not a GEMM'",
    "UNDETERMINED": "UNDETERMINED: the specification does not decide (spec question)",
}


def load(path, default=None):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def executed_text(rep_case):
    """What the framework actually did with the case, from a report entry."""
    if not rep_case:
        return "NOT EXECUTED by the framework in the latest report"
    a = rep_case.get("actual", {})
    st = rep_case.get("stages", {})
    ran = [s for s in ("cpu", "frontend", "discovery", "lowering", "driver", "execute") if s in st]
    not_run = st.get("not_run", {})
    parts = ["verdict **%s**" % rep_case["verdict"], "stages run: %s" % (", ".join(ran) or "none")]
    if not_run:
        parts.append("not run: " + "; ".join("%s (%s)" % (k, v) for k, v in not_run.items()))
    if a.get("driver") not in (None, "not_applicable"):
        parts.append("driver %s" % a.get("driver"))
    if a.get("execute") not in (None, "not_applicable"):
        parts.append("program %s" % a.get("execute"))
    if a.get("invocations") is not None:
        parts.append("%s invocation(s)" % a.get("invocations"))
    if a.get("lowering_result"):
        parts.append("lowering %s" % a.get("lowering_result"))
    return "; ".join(parts)


def forms_text(e):
    f = e.get("index_forms")
    if not f:
        return "(MLIR-level case: see the file)"
    ops = "; ".join("%s: %s" % (n, "/".join(k)) for n, k in f["operands"].items())
    sh = "; ".join("%s (%s): %s" % (g, v["operands"], v["relation"]) for g, v in f.get("shared", {}).items())
    return ops + ((" -- shared coordinates: " + sh) if sh else "")


def loops_text(e):
    if e.get("loop_summary"):
        return "; ".join(e["loop_summary"])
    return "(MLIR-level case: see the file)"


def purpose(e):
    note = (e.get("math_note") or "").strip().split("\n")[0]
    return "%s [%s]%s" % (e["name"], e["category"], (": " + note) if note else "")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", default=os.path.join(ROOT, "reports", "latest_soft.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "showcase", "INVENTORY.md"))
    a = ap.parse_args()
    manifest = load(os.path.join(ROOT, "showcase", "manifest.json"))
    if not manifest:
        print("no showcase/manifest.json", file=sys.stderr)
        return 2
    report = load(a.report, None)
    rep = {c["id"]: c for c in report["cases"]} if report else {}
    entries = manifest["showcase"] + manifest["extended"]

    def group_of(e):
        n = e["id"]
        if n.startswith("mlir_"):
            return "mlir"
        if n.startswith("ext_"):
            return "extended"
        num = int(n.split("_")[1])
        return "hundred" if num <= 100 else "boundary"

    groups = {"hundred": [], "boundary": [], "extended": [], "mlir": []}
    for e in entries:
        groups[group_of(e)].append(e)

    inv = []
    L = ["# Showcase inventory", ""]
    L.append("Generated by `scripts/inventory.py` from `showcase/manifest.json` (the specification "
             "and prediction layers) and `%s` (what the framework actually ran%s). The expectation "
             "of a case is set by the mathematics and README.md section 2, never by the compiler's "
             "output; a case the specification does not decide says so (spec question) instead of "
             "being sorted into positive or negative." % (
                 os.path.relpath(a.report, ROOT),
                 ", %s, %s" % (report["timestamp"], report["mode"]) if report else " -- no report found"))
    L.append("")
    counts = {}
    for e in entries:
        counts[e["expected"]["recognition"]] = counts.get(e["expected"]["recognition"], 0) + 1
    L.append("Cases: %d (the hundred: %d, boundary cases added after it: %d, extended: %d, MLIR-level: %d). "
             "Specified expectation: %s." % (
                 len(entries), len(groups["hundred"]), len(groups["boundary"]), len(groups["extended"]),
                 len(groups["mlir"]), ", ".join("%s %d" % kv for kv in sorted(counts.items()))))
    L.append("")
    if report:
        vc = {}
        for e in entries:
            v = rep.get(e["id"], {}).get("verdict", "NOT EXECUTED")
            vc[v] = vc.get(v, 0) + 1
        L.append("Execution in the latest report: " + ", ".join("%s %d" % kv for kv in sorted(vc.items())) + ".")
        L.append("")
    sq = manifest.get("spec_questions", {})
    if sq:
        L.append("## Open spec questions (README.md section 2)")
        L.append("")
        for k, v in sq.items():
            users = [e["id"] for e in entries if e["expected"].get("spec_question") == k]
            L.append("- **%s**: %s  \n  cases: %s" % (k, v, ", ".join(users) or "none"))
        L.append("")
    titles = {"hundred": "The hundred (case_001 .. case_100)", "boundary": "Boundary cases (case_101 ..)",
              "extended": "Extended cases (ext_*)", "mlir": "MLIR-level cases (mlir_*)"}
    for g in ("hundred", "boundary", "extended", "mlir"):
        L.append("## " + titles[g])
        L.append("")
        for e in groups[g]:
            r = rep.get(e["id"])
            spec = e["expected"]
            row = {
                "id": e["id"], "file": "showcase/" + e["file"], "kind": e.get("kind", "c"),
                "purpose": purpose(e),
                "expected": spec["recognition"], "expected_text": EXPECT_TEXT[spec["recognition"]],
                "basis": spec["basis"], "classification": e.get("classification"),
                "index_forms": e.get("index_forms"), "loops": e.get("loop_summary"),
                "executed": executed_text(r), "verdict": r["verdict"] if r else None,
                "spec_question": spec.get("spec_question"),
                "issue": e.get("issue"),
            }
            inv.append(row)
            L.append("### %s — `%s`" % (e["id"], row["file"]))
            L.append("")
            L.append("- purpose: %s" % row["purpose"])
            L.append("- expected (specification): %s" % row["expected_text"])
            L.append("- basis: %s" % row["basis"])
            L.append("- classification vs the current implementation: %s%s" % (
                row["classification"], " (%s)" % row["issue"] if row["issue"] else ""))
            L.append("- affine index forms: %s" % forms_text(e))
            L.append("- loop bounds and steps: %s" % loops_text(e))
            L.append("- executed by the framework: %s" % row["executed"])
            L.append("- spec unclear: %s" % (("yes -- %s: %s" % (row["spec_question"], sq.get(row["spec_question"], "")))
                                             if row["spec_question"] else "no"))
            L.append("")
    with open(a.out, "w") as f:
        f.write("\n".join(L) + "\n")
    with open(os.path.join(os.path.dirname(a.out), "inventory.json"), "w") as f:
        json.dump({"report": os.path.relpath(a.report, ROOT) if report else None,
                   "report_timestamp": report["timestamp"] if report else None,
                   "cases": inv}, f, indent=1)
    print("wrote %s and inventory.json (%d cases, %d with execution evidence)" % (
        os.path.relpath(a.out, ROOT), len(inv), sum(1 for r in inv if r["verdict"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
