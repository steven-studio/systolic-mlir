  RUN(n_only, 42, 54, 63, 3);
  RUN(k_only, 77, 55, 35, 1);
  RUN(k_only_outer, 77, 55, 35, 1);
  RUN(mn, 60, 54, 90, 6);
  RUN(mnk, 70, 63, 90, 6);
