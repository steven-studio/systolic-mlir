`timescale 1ns / 1ps

/*
 * ============================================================
 * led_test -- 外接 LED 的煙霧測試(不含任何設計邏輯)
 * ============================================================
 *
 * 目的:在把 LED 拿來當診斷工具之前,先證明 LED 本身、接觸、
 * 腳位約束都是好的。這禮拜已經有五次是「工具本身壞掉」而不是
 * 設計壞掉 -- 新工具上線前先驗工具。
 *
 * 四顆燈,兩兩成對,構成一個「鑑別診斷」:
 *
 *              恆亮          心跳(約 1.5 Hz)
 *   板上內建   LD0           LD1          <- 對照組:不經任何接線
 *   外接       JB pin 4      JB pin 10    <- 受測組:經排針與跳線
 *
 * 判讀:
 *   四顆全亮/全閃 -> 外接 LED 完全正常,可以拿去當診斷工具
 *   只有 LD0/LD1 動 -> bitstream 與時脈都好,問題在外接那一側
 *                      (極性反了?腳插錯格?接觸不良?LED 燒了?)
 *   四顆都不動      -> 不是 LED 的問題:bitstream 沒燒進去,
 *                      或時脈沒進來 -- 先回頭查燒錄
 *   恆亮的亮、心跳的不閃 -> 時脈死了(恆亮那顆不需要時脈)
 *
 * 心跳那顆的價值:它證明的不只是「燈會亮」,而是「時脈在跑」。
 * 恆亮只證明 I/O 通,心跳證明整個同步邏輯活著。
 * ============================================================
 */
module led_test (
    input  logic       clk,       // R4, 100 MHz

    /* 外接:JB pin 4 (jb[3], W7) 與 pin 10 (jb[7], Y7)。
     * 這兩支是 Pmod 上「與 GND 腳相鄰」的訊號腳,LED 可以直接
     * 跨在 pin4-pin5 與 pin10-pin11 上,不需要麵包板。 */
    output logic [1:0] jb_led,

    /* 板上內建 LD0 / LD1,作為對照組。 */
    output logic [1:0] led
);

    /*
     * 100 MHz / 2^25 = 每 0.336 秒翻轉一次 -> 約 1.5 Hz。
     *
     * 初始值 '0 在 7-series 是有效的:FF 於 configuration 當下
     * 就載入宣告值,不需要 reset。這顆測試刻意不接 BTNC --
     * 少一個「忘了按 reset」的失敗模式。
     */
    logic [25:0] cnt = '0;

    always_ff @(posedge clk)
        cnt <= cnt + 1'b1;

    wire beat = cnt[25];

    assign jb_led[0] = 1'b1;    // 外接:恆亮
    assign jb_led[1] = beat;    // 外接:心跳

    assign led[0]    = 1'b1;    // 內建:恆亮
    assign led[1]    = beat;    // 內建:心跳

endmodule
